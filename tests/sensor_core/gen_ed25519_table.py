#!/usr/bin/env python3
"""Generate components/cs_sensor/cs_ed25519_table.h, the fixed-base comb table.

Table k (0 <= k < TABLES) holds j * 16^(STRIDE k) * B for j = 1..8, where B is the
Ed25519 base point and STRIDE = 64 / TABLES, as (y + x, y - x, 2 d x y) mod p, each
32 bytes little-endian, packed into 24 little-endian 32-bit words per entry.

  python3 gen_ed25519_table.py            # write the header
  python3 gen_ed25519_table.py --check    # fail if the committed header differs
"""

import argparse
import pathlib
import sys

TABLES = 16

P = 2**255 - 19
D = -121665 * pow(121666, P - 2, P) % P
B = (
    15112221349535400772501151409588531511454012693041857206046113283949847762202,
    46316835694926478169428394003475163141307993866256225615783033603165251855960,
)
OUT = pathlib.Path(__file__).resolve().parents[2] / "components" / "cs_sensor" / "cs_ed25519_table.h"


def add(p, q):
    (x1, y1), (x2, y2) = p, q
    t = D * x1 * x2 * y1 * y2 % P
    x = (x1 * y2 + x2 * y1) * pow(1 + t, P - 2, P) % P
    y = (y1 * y2 + x1 * x2) * pow(1 - t, P - 2, P) % P
    return x, y


def words(v):
    b = v.to_bytes(32, "little")
    return [int.from_bytes(b[i : i + 4], "little") for i in range(0, 32, 4)]


def render():
    stride = 64 // TABLES
    lines = [
        "#pragma once",
        "",
        "// Generated by tests/sensor_core/gen_ed25519_table.py; do not edit.",
        f"// Table k holds j * 16^({stride} k) * B for j = 1..8 as (y + x, y - x, 2 d x y),",
        "// each 32 bytes little-endian in 8 little-endian words.",
        "",
        "#include <cstdint>",
        "",
        "namespace esphome::cs_sensor::ed25519_table {",
        "",
        f"constexpr int TABLES = {TABLES};",
        f"constexpr int STRIDE = {stride};  // radix-16 digits between tables",
        "",
        "const uint32_t COMB[TABLES][8][24] = {",
    ]
    base = B
    for _ in range(TABLES):
        lines.append("    {")
        q = base
        for _ in range(8):
            x, y = q
            lines.append("        {")
            for v in ((y + x) % P, (y - x) % P, 2 * D * x * y % P):
                lines.append("            " + ", ".join(f"0x{w:08x}" for w in words(v)) + ",")
            lines.append("        },")
            q = add(q, base)
        lines.append("    },")
        for _ in range(4 * stride):
            base = add(base, base)
    lines += ["};", "", "}  // namespace esphome::cs_sensor::ed25519_table", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT} is out of date; run {pathlib.Path(__file__).name}")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
