#!/usr/bin/env python3
"""Generate vectors.inc for the sensor core tests from spec/vectors.

Run from anywhere:  python3 tests/sensor_core/gen_vectors.py
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.normpath(os.path.join(HERE, "..", "..", "spec"))
sys.path.insert(0, os.path.join(SPEC, "tools"))
sys.dont_write_bytecode = True
import csframe  # noqa: E402


def load(name):
    with open(os.path.join(SPEC, "vectors", name)) as f:
        return json.load(f)


def s(v):
    return "nullptr" if v is None else f'"{v}"'


def raw_value(d):
    """The value bytes of a decoded reading, as encoded (without a class 3 length)."""
    kind, value = d["kind"], d["value"]
    if isinstance(value, str):
        return value.encode().hex() if kind == 0xC1 else value
    return csframe.encode_reading(d["channel"], kind, value)[2:].hex()


def main():
    frames = load("frame-v1.json")
    payload = load("payload-v1.json")
    pairing = load("pairing-v1.json")
    out = ["// Generated by gen_vectors.py from spec/vectors. Do not edit.", "#pragma once", ""]

    inp, der = frames["inputs"], frames["derived"]
    for key in ("k_root", "dev_eui", "k_net", "sensor_ephemeral_private", "server_ephemeral_private"):
        out.append(f'static const char *V_{key.upper()} = "{inp[key]}";')
    out.append(f"static const unsigned V_TIME = {inp['time']}u;")
    out.append(f"static const unsigned V_EPOCH = {inp['epoch']}u;")
    out.append(f'static const char *V_ROOT_K_ENC = "{der["root"]["k_enc"]}";')
    out.append(f'static const char *V_ROOT_K_DEV_TAG = "{der["root"]["k_dev_tag"]}";')
    out.append(f'static const char *V_SENSOR_PUB = "{der["sensor_ephemeral_public"]}";')
    out.append(f'static const char *V_SERVER_PUB = "{der["server_ephemeral_public"]}";')
    out.append(f'static const char *V_K_SESSION = "{der["k_session"]}";')
    out.append(f'static const char *V_SESSION_K_ENC = "{der["session"]["k_enc"]}";')
    out.append(f'static const char *V_SESSION_K_DEV_TAG = "{der["session"]["k_dev_tag"]}";')
    out.append(f'static const char *V_K_NET_ROUTE = "{der["k_net_route"]}";')
    out.append("struct TagVector { unsigned epoch; const char *net; const char *dev; };")
    out.append("static const TagVector TAG_VECTORS[] = {")
    for e in sorted(der["net_tag"]):
        out.append(f'  {{{e}u, "{der["net_tag"][e]}", "{der["dev_tag"][e]}"}},')
    out.append("};")
    out.append("")

    out.append("struct FrameVector { const char *name; bool root; int type; unsigned fcnt; const char *net_tag;"
               " const char *dev_tag; const char *plaintext; const char *frame; };")
    out.append("static const FrameVector FRAME_VECTORS[] = {")
    for f in frames["frames"]:
        out.append(f'  {{"{f["name"]}", {"true" if f["keys"] == "root" else "false"}, {f["type"]}, {f["fcnt"]}u, '
                   f'"{f["net_tag"]}", "{f["dev_tag"]}", "{f["plaintext"]}", "{f["frame"]}"}},')
    out.append("};")
    out.append("")

    out.append("struct DecodedReading { int channel; int kind; const char *raw; bool is_int; long long value; };")
    out.append("struct PayloadVector { const char *name; const char *encoded; int count; DecodedReading readings[4]; };")
    out.append("static const PayloadVector PAYLOAD_VECTORS[] = {")
    for p in payload["readings"]:
        items = []
        for d in p["decoded"]:
            is_int = isinstance(d["value"], int)
            items.append(f'{{{d["channel"]}, {d["kind"]}, "{raw_value(d)}", {"true" if is_int else "false"}, '
                         f'{d["value"] if is_int else 0}LL}}')
        out.append(f'  {{"{p["name"]}", "{p["encoded"]}", {len(items)}, {{{", ".join(items)}}}}},')
    out.append("};")
    out.append("")

    out.append("struct InvalidFrameVector { const char *name; const char *reason; const char *frame; };")
    out.append("static const InvalidFrameVector INVALID_FRAME_VECTORS[] = {")
    for f in frames["invalid"]:
        assert f["keys"] == "session"
        out.append(f'  {{"{f["name"]}", "{f["reason"]}", "{f["frame"]}"}},')
    out.append("};")
    out.append("struct InvalidPayloadVector { const char *name; const char *reason; const char *encoded; };")
    out.append("static const InvalidPayloadVector INVALID_PAYLOAD_VECTORS[] = {")
    for p in payload["invalid"]:
        out.append(f'  {{"{p["name"]}", "{p["reason"]}", "{p["encoded"]}"}},')
    out.append("};")
    out.append("")

    good = pairing["valid"][0]
    out.append(f'static const char *V_PAIRING_CODE = "{good["code"]}";')
    out.append(f'static const char *V_PAIRING_REGION = "{good["parsed"]["region"]}";')
    out.append(f'static const char *V_PAIRING_PROFILE = "{good["parsed"]["profile"]}";')
    out.append("")

    out.append("struct RootFloorStep { const char *event; unsigned fcnt; const char *priv; const char *frame;"
               " const char *result; unsigned root_floor; const char *k_session; };")
    out.append("static const RootFloorStep ROOT_FLOOR_STEPS[] = {")
    for st in pairing["root_floor"]["sequence"]:
        out.append(f'  {{"{st["event"]}", {st.get("fcnt", 0)}u, {s(st.get("sensor_ephemeral_private"))}, '
                   f'{s(st.get("frame"))}, {s(st.get("result"))}, {st.get("root_floor", 0)}u, '
                   f'{s(st.get("k_session"))}}},')
    out.append("};")

    with open(os.path.join(HERE, "vectors.inc"), "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
