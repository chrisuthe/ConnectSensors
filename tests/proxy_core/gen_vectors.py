#!/usr/bin/env python3
"""Generate vectors.inc for the proxy core tests from spec/vectors.

Run from anywhere:  python3 tests/proxy_core/gen_vectors.py
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.normpath(os.path.join(HERE, "..", "..", "spec"))
sys.path.insert(0, os.path.join(SPEC, "tools"))
sys.dont_write_bytecode = True
import csframe  # noqa: E402


def load(name):
    with open(os.path.join(SPEC, "vectors", name)) as f:
        return json.load(f)


def main():
    frames = load("frame-v1.json")
    env = load("proxy-envelope-v1.json")
    out = ["// Generated by gen_vectors.py from spec/vectors. Do not edit.", "#pragma once", ""]

    out.append("struct FrameVector { const char *name; int type; const char *hex; };")
    out.append("static const FrameVector FRAME_VECTORS[] = {")
    for f in frames["frames"]:
        out.append(f'  {{"{f["name"]}", {f["type"]}, "{f["frame"]}"}},')
    out.append("};")
    out.append("struct InvalidFrameVector { const char *name; bool proxy_discards; const char *hex; };")
    out.append("static const InvalidFrameVector INVALID_FRAME_VECTORS[] = {")
    for f in frames["invalid"]:
        out.append(f'  {{"{f["name"]}", {"true" if f["proxy_discards"] else "false"}, "{f["frame"]}"}},')
    out.append("};")
    out.append("")

    out.append(f'static const char *PROXY_KEY_HEX = "{env["inputs"]["proxy_key"]}";')
    out.append(f'static const char *PROXY_ID_HEX = "{env["inputs"]["proxy_id"]}";')
    out.append("struct EnvelopeVector { const char *name; int type; unsigned boot_id; unsigned seq;"
               " const char *body; const char *message; };")
    out.append("static const EnvelopeVector ENVELOPE_VECTORS[] = {")
    for m in env["messages"]:
        out.append(f'  {{"{m["name"]}", {m["type"]}, {m["boot_id"]}u, {m["seq"]}u, "{m["body"]}", "{m["message"]}"}},')
    out.append("};")
    out.append("")

    out.append("struct AirtimeVector { int len; int sf; int bw; unsigned us; };")
    out.append("static const AirtimeVector AIRTIME_VECTORS[] = {")
    # SF11 and SF12 at 125 kHz, SF10 at 62.5 kHz and SF12 at 250 kHz use the low data rate optimization.
    for n in (23, 31, 55, 65, 86):
        for sf, bw in ((9, 500000), (9, 125000), (7, 125000), (11, 125000), (12, 125000), (10, 62500),
                       (12, 250000), (12, 500000)):
            us = round(csframe.airtime_ms(n, sf, bw) * 1000)
            out.append(f"  {{{n}, {sf}, {bw}, {us}u}},")
    out.append("};")

    with open(os.path.join(HERE, "vectors.inc"), "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
