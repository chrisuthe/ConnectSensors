"""ConnectSensors protocol v1 for network servers.

The implementation is the spec's reference, ``spec/tools/csframe.py``, shipped as
``connectsensors._csframe``. This module is the supported surface; names match
csframe's so the spec and the package read the same.
"""

import importlib.util
import os
import sys

if importlib.util.find_spec(__name__ + "._csframe") is None:
    # An editable install or the checkout: only the wheel has _csframe.py, so load the
    # spec's file in its place.
    _spec = importlib.util.spec_from_file_location(
        __name__ + "._csframe",
        os.path.join(os.path.dirname(__file__), "..", "..", "spec", "tools", "csframe.py"),
    )
    assert _spec is not None and _spec.loader is not None
    _module = importlib.util.module_from_spec(_spec)
    sys.modules[_spec.name] = _module
    _spec.loader.exec_module(_module)

